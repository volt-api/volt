const std = @import("std");
const mem = std.mem;
const Allocator = mem.Allocator;
const VoltFile = @import("volt_file.zig");

// ── API Documentation Generator ─────────────────────────────────────────
// Generates Markdown and HTML documentation from collections of .volt files.
// Creates endpoint reference docs with method, URL, headers, body examples,
// and test expectations.

pub const HeaderDoc = struct {
    name: []const u8,
    value: []const u8,
};

pub const DocEntry = struct {
    name: []const u8,
    method: []const u8,
    url: []const u8,
    description: ?[]const u8 = null,
    headers: std.ArrayList(HeaderDoc),
    body_type: []const u8,
    body_example: ?[]const u8 = null,
    auth_type: []const u8,
    tests: std.ArrayList([]const u8),

    pub fn init(allocator: Allocator) DocEntry {
        return .{
            .name = "",
            .method = "GET",
            .url = "",
            .headers = std.ArrayList(HeaderDoc).init(allocator),
            .body_type = "none",
            .auth_type = "none",
            .tests = std.ArrayList([]const u8).init(allocator),
        };
    }

    pub fn deinit(self: *DocEntry) void {
        self.headers.deinit();
        self.tests.deinit();
    }
};

/// Generate Markdown documentation from a list of parsed requests
pub fn generateMarkdown(allocator: Allocator, entries: []const DocEntry, title: []const u8) ![]const u8 {
    var buf = std.ArrayList(u8).init(allocator);
    const writer = buf.writer();

    try writer.print("# API Documentation: {s}\n\n", .{title});
    try writer.writeAll("Generated by Volt API Client\n\n");
    try writer.writeAll("---\n\n");

    // Table of contents
    if (entries.len > 1) {
        try writer.writeAll("## Table of Contents\n\n");
        for (entries, 0..) |entry, i| {
            try writer.print("{d}. **{s}** `{s}`\n", .{ i + 1, entry.method, entry.url });
        }
        try writer.writeAll("\n---\n\n");
    }

    for (entries) |entry| {
        // Section heading
        try writer.print("## {s} {s}\n\n", .{ entry.method, entry.url });

        // File name
        if (entry.name.len > 0) {
            try writer.print("**File:** `{s}`\n\n", .{entry.name});
        }

        // Description
        if (entry.description) |desc| {
            try writer.print("{s}\n\n", .{desc});
        }

        // Authentication
        if (!mem.eql(u8, entry.auth_type, "none")) {
            try writer.print("**Authentication:** {s}\n\n", .{entry.auth_type});
        }

        // Headers table
        if (entry.headers.items.len > 0) {
            try writer.writeAll("### Headers\n\n");
            try writer.writeAll("| Header | Value |\n");
            try writer.writeAll("|--------|-------|\n");
            for (entry.headers.items) |h| {
                try writer.print("| {s} | {s} |\n", .{ h.name, h.value });
            }
            try writer.writeAll("\n");
        }

        // Body
        if (entry.body_example) |body| {
            try writer.writeAll("### Body\n\n");
            try writer.print("**Type:** `{s}`\n\n", .{entry.body_type});
            // Determine code block language
            const lang = if (mem.eql(u8, entry.body_type, "json"))
                "json"
            else if (mem.eql(u8, entry.body_type, "xml"))
                "xml"
            else
                "";
            try writer.print("```{s}\n{s}\n```\n\n", .{ lang, body });
        }

        // Tests
        if (entry.tests.items.len > 0) {
            try writer.writeAll("### Tests\n\n");
            for (entry.tests.items) |t| {
                try writer.print("- {s}\n", .{t});
            }
            try writer.writeAll("\n");
        }

        try writer.writeAll("---\n\n");
    }

    // Footer
    try writer.print("*{d} endpoint(s) documented.*\n", .{entries.len});

    return buf.toOwnedSlice();
}

/// Generate HTML documentation (wraps markdown-like content in HTML template)
