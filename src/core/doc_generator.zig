    try writer.writeAll("      border-radius: 4px; font-weight: bold; font-size: 0.85rem;\n");
    try writer.writeAll("      margin-right: 0.5rem; }\n");
    try writer.writeAll("    .method-GET { background: #2ecc71; color: #000; }\n");
    try writer.writeAll("    .method-POST { background: #3498db; color: #fff; }\n");
    try writer.writeAll("    .method-PUT { background: #f39c12; color: #000; }\n");
    try writer.writeAll("    .method-PATCH { background: #e67e22; color: #000; }\n");
    try writer.writeAll("    .method-DELETE { background: #e74c3c; color: #fff; }\n");
    try writer.writeAll("    .method-HEAD { background: #9b59b6; color: #fff; }\n");
    try writer.writeAll("    .method-OPTIONS { background: #95a5a6; color: #000; }\n");
