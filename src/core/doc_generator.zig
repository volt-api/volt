    try writer.writeAll("    h2 { color: #ffffff; margin: 1.5rem 0 0.5rem; font-size: 1.4rem; }\n");
    try writer.writeAll("    h3 { color: #b0b0b0; margin: 1rem 0 0.5rem; font-size: 1.1rem; }\n");
