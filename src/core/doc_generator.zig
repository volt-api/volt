    try writer.writeAll("    code { background: #0f3460; padding: 0.2rem 0.4rem; border-radius: 3px;\n");
    try writer.writeAll("      font-family: 'Fira Code', monospace; font-size: 0.9rem; }\n");
    try writer.writeAll("    pre { background: #0f3460; padding: 1rem; border-radius: 6px;\n");
    try writer.writeAll("      overflow-x: auto; margin: 0.5rem 0; }\n");
    try writer.writeAll("    pre code { background: none; padding: 0; }\n");
    try writer.writeAll("    .test-item { padding: 0.25rem 0; }\n");
    try writer.writeAll("    .test-check { color: #2ecc71; margin-right: 0.5rem; }\n");
    try writer.writeAll("    .auth-badge { background: #e74c3c; color: #fff; padding: 0.15rem 0.5rem;\n");
    try writer.writeAll("      border-radius: 3px; font-size: 0.8rem; }\n");
    try writer.writeAll("    .filename { color: #666; font-size: 0.85rem; font-style: italic; }\n");
    try writer.writeAll("    hr { border: none; border-top: 1px solid #2a2a4a; margin: 2rem 0; }\n");
    try writer.writeAll("    .footer { color: #555; font-size: 0.85rem; margin-top: 2rem; text-align: center; }\n");
    try writer.writeAll("  </style>\n");
    try writer.writeAll("</head>\n<body>\n");
    try writer.writeAll("  <div class=\"container\">\n");

    // Title
    try writer.print("    <h1>{s}</h1>\n", .{title});
    try writer.writeAll("    <p class=\"subtitle\">Generated by Volt API Client</p>\n");
    try writer.writeAll("    <hr>\n\n");

    // Entries
    for (entries) |entry| {
        try writer.writeAll("    <div class=\"endpoint\">\n");

        // Method badge + URL
        try writer.print("      <h2><span class=\"method-badge method-{s}\">{s}</span> ", .{ entry.method, entry.method });
        try writer.print("<span class=\"url\">{s}</span></h2>\n", .{entry.url});

        // Filename
        if (entry.name.len > 0) {
            try writer.print("      <p class=\"filename\">{s}</p>\n", .{entry.name});
        }

        // Description
        if (entry.description) |desc| {
            try writer.print("      <p>{s}</p>\n", .{desc});
        }

        // Auth
        if (!mem.eql(u8, entry.auth_type, "none")) {
            try writer.print("      <p><span class=\"auth-badge\">{s}</span></p>\n", .{entry.auth_type});
        }

        // Headers
        if (entry.headers.items.len > 0) {
            try writer.writeAll("      <h3>Headers</h3>\n");
            try writer.writeAll("      <table>\n");
            try writer.writeAll("        <tr><th>Header</th><th>Value</th></tr>\n");
            for (entry.headers.items) |h| {
                try writer.print("        <tr><td><code>{s}</code></td><td><code>{s}</code></td></tr>\n", .{ h.name, h.value });
            }
            try writer.writeAll("      </table>\n");
        }

        // Body
        if (entry.body_example) |body| {
            try writer.writeAll("      <h3>Body</h3>\n");
            try writer.print("      <p>Type: <code>{s}</code></p>\n", .{entry.body_type});
            try writer.writeAll("      <pre><code>");
            // HTML-escape the body
            for (body) |c| {
                switch (c) {
                    '<' => try writer.writeAll("&lt;"),
                    '>' => try writer.writeAll("&gt;"),
                    '&' => try writer.writeAll("&amp;"),
                    '"' => try writer.writeAll("&quot;"),
                    else => try writer.writeByte(c),
                }
            }
            try writer.writeAll("</code></pre>\n");
        }

        // Tests
        if (entry.tests.items.len > 0) {
            try writer.writeAll("      <h3>Tests</h3>\n");
            for (entry.tests.items) |t| {
                try writer.print("      <div class=\"test-item\"><span class=\"test-check\">&#10003;</span>{s}</div>\n", .{t});
            }
        }

        try writer.writeAll("    </div>\n\n");
    }

    // Footer
    try writer.print("    <p class=\"footer\">{d} endpoint(s) documented</p>\n", .{entries.len});
    try writer.writeAll("  </div>\n");
    try writer.writeAll("</body>\n</html>\n");

    return buf.toOwnedSlice();
}

/// Build DocEntry from a VoltRequest
pub fn fromRequest(allocator: Allocator, request: *const VoltFile.VoltRequest, filename: []const u8) !DocEntry {
    var entry = DocEntry.init(allocator);

    entry.name = try allocator.dupe(u8, filename);
    entry.method = request.method.toString(); // comptime string literal, safe
    entry.url = try allocator.dupe(u8, request.url);
    entry.body_type = request.body_type.toString(); // comptime string literal, safe
    entry.body_example = if (request.body) |b| try allocator.dupe(u8, b) else null;
    entry.auth_type = request.auth.type.toString(); // comptime string literal, safe

    // Copy headers (dupe strings since request will be freed)
    for (request.headers.items) |h| {
        try entry.headers.append(.{
            .name = try allocator.dupe(u8, h.name),
            .value = try allocator.dupe(u8, h.value),
        });
    }

    // Build test descriptions
    for (request.tests.items) |t| {
        const desc = try std.fmt.allocPrint(allocator, "{s} {s} {s}", .{ t.field, t.operator, t.value });
        try entry.tests.append(desc);
    }

    return entry;
}

/// Scan a directory and generate Markdown docs for all .volt files found
pub fn generateDocsFromDir(allocator: Allocator, dir_path: []const u8, title: []const u8) ![]const u8 {
    var entries = std.ArrayList(DocEntry).init(allocator);
    defer {
        for (entries.items) |*e| {
            // Free owned strings
            allocator.free(e.name);
            allocator.free(e.url);
            if (e.body_example) |b| allocator.free(b);
            for (e.headers.items) |h| {
                allocator.free(h.name);
                allocator.free(h.value);
            }
            for (e.tests.items) |t| {
                allocator.free(t);
            }
            e.deinit();
        }
        entries.deinit();
    }

    // Open directory and scan for .volt files
    var dir = std.fs.cwd().openDir(dir_path, .{ .iterate = true }) catch {
        // If directory can't be opened, return error description as markdown
        var buf = std.ArrayList(u8).init(allocator);
        const writer = buf.writer();
        try writer.print("# API Documentation: {s}\n\n", .{title});
        try writer.writeAll("Error: Could not open the specified directory.\n");
        return buf.toOwnedSlice();
    };
    defer dir.close();

    var iter = dir.iterate();
    while (iter.next() catch null) |file_entry| {
        if (file_entry.kind != .file) continue;
        if (!mem.endsWith(u8, file_entry.name, ".volt")) continue;

        // Read the file
        const file = dir.openFile(file_entry.name, .{}) catch continue;
        defer file.close();

        const content = file.readToEndAlloc(allocator, 1024 * 1024) catch continue;
        defer allocator.free(content);

        // Parse the .volt file
        var request = VoltFile.parse(allocator, content) catch continue;
        defer request.deinit();

        // Build doc entry
        var doc_entry = fromRequest(allocator, &request, file_entry.name) catch continue;
        entries.append(doc_entry) catch {
            for (doc_entry.tests.items) |t| {
                allocator.free(t);
            }
            doc_entry.deinit();
            continue;
        };
    }

    return generateMarkdown(allocator, entries.items, title);
}

// ── Tests ───────────────────────────────────────────────────────────────

test "generate markdown from doc entry" {
    var entry = DocEntry.init(std.testing.allocator);
    defer entry.deinit();
    entry.name = "get-users.volt";
    entry.method = "GET";
    entry.url = "/api/users";
    entry.body_type = "none";
    entry.auth_type = "bearer";

    try entry.headers.append(.{ .name = "Accept", .value = "application/json" });
    try entry.headers.append(.{ .name = "Authorization", .value = "Bearer token123" });
    try entry.tests.append("status equals 200");
    try entry.tests.append("body contains users");

    const doc_entries = [_]DocEntry{entry};
    const result = try generateMarkdown(std.testing.allocator, &doc_entries, "My API");
    defer std.testing.allocator.free(result);

    try std.testing.expect(mem.indexOf(u8, result, "# API Documentation: My API") != null);
    try std.testing.expect(mem.indexOf(u8, result, "## GET /api/users") != null);
    try std.testing.expect(mem.indexOf(u8, result, "get-users.volt") != null);
    try std.testing.expect(mem.indexOf(u8, result, "| Accept | application/json |") != null);
    try std.testing.expect(mem.indexOf(u8, result, "bearer") != null);
    try std.testing.expect(mem.indexOf(u8, result, "status equals 200") != null);
    try std.testing.expect(mem.indexOf(u8, result, "body contains users") != null);
}

test "fromRequest conversion" {
    var req = VoltFile.VoltRequest.init(std.testing.allocator);
    defer req.deinit();
    req.method = .POST;
    req.url = "https://api.example.com/users";
    req.body_type = .json;
    req.body = "{\"name\": \"test\"}";
    try req.addHeader("Content-Type", "application/json");
    try req.tests.append(.{ .field = "status", .operator = "equals", .value = "201" });

    var entry = try fromRequest(std.testing.allocator, &req, "create-user.volt");
    defer {
        std.testing.allocator.free(entry.name);
        std.testing.allocator.free(entry.url);
        if (entry.body_example) |b| std.testing.allocator.free(b);
        for (entry.headers.items) |h| {
            std.testing.allocator.free(h.name);
            std.testing.allocator.free(h.value);
        }
        for (entry.tests.items) |t| {
            std.testing.allocator.free(t);
        }
        entry.deinit();
    }

    try std.testing.expectEqualStrings("POST", entry.method);
    try std.testing.expectEqualStrings("https://api.example.com/users", entry.url);
    try std.testing.expectEqualStrings("create-user.volt", entry.name);
    try std.testing.expectEqualStrings("json", entry.body_type);
    try std.testing.expectEqualStrings("{\"name\": \"test\"}", entry.body_example.?);
    try std.testing.expectEqual(@as(usize, 1), entry.headers.items.len);
    try std.testing.expectEqualStrings("Content-Type", entry.headers.items[0].name);
    try std.testing.expectEqual(@as(usize, 1), entry.tests.items.len);
    try std.testing.expect(mem.indexOf(u8, entry.tests.items[0], "status equals 201") != null);
}
